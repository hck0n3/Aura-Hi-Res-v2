package iad1tya.echo.music.eq.autoeq

import android.content.Context
import iad1tya.echo.music.eq.data.FilterType
import java.lang.ref.SoftReference
import java.util.zip.GZIPInputStream

/** The kind of rig an AutoEq result was measured on (its `results/<source>/<rig>` folder). */
enum class AutoEqRigType(val code: String) {
    IN_EAR("in-ear"),
    OVER_EAR("over-ear"),
    EARBUD("earbud"),
    UNKNOWN("");

    companion object {
        fun fromCode(code: String): AutoEqRigType = entries.firstOrNull { it.code == code && code.isNotEmpty() } ?: UNKNOWN
    }
}

/**
 * One measured headphone of the bundled catalogue. [bandsRaw] is kept as text and parsed only when the profile is used
 * ([toProfile]), so loading the ~8,700 rows for a name search costs no band objects.
 */
data class AutoEqOfflineEntry(
    val name: String,
    val source: String,
    val type: AutoEqRigType,
    /** AutoEq's own «Recommended Results» (`results/README.md`) pick for this model: its most accurate measurement. */
    val recommended: Boolean,
    val preampDb: Double,
    val bandsRaw: String,
) {
    fun toProfile(): AutoEqProfile = AutoEqProfile(preampDb, AutoEqOfflineCatalog.parseBands(bandsRaw))

    /** The same one-line format the asset uses, so a device assignment keeps its own copy of the curve. */
    fun toLine(): String = listOf(name, source, type.code, if (recommended) "1" else "0", preampDb.toString(), bandsRaw)
        .joinToString("\t")
}

/**
 * Offline AutoEq catalogue (registry row 916): `assets/autoeq_profiles.tsv.gz`, generated by
 * `scripts/build_autoeq_profiles.py` from jaakkopasanen/AutoEq (MIT) results. Every model's parametric filters ship with
 * the app, so matching a Bluetooth name and applying its correction never needs the network.
 */
object AutoEqOfflineCatalog {

    const val ASSET_NAME = "autoeq_profiles.tsv.gz"

    @Volatile private var cache: SoftReference<List<AutoEqOfflineEntry>>? = null

    /** One row: `name \t source \t type \t recommended \t preamp \t bands`. Null for a comment or a malformed line. */
    fun parseLine(line: String): AutoEqOfflineEntry? {
        if (line.isBlank() || line.startsWith("#")) return null
        val p = line.split('\t')
        if (p.size != 6) return null
        val preamp = p[4].toDoubleOrNull() ?: return null
        if (p[0].isBlank() || p[5].isBlank()) return null
        return AutoEqOfflineEntry(p[0], p[1], AutoEqRigType.fromCode(p[2]), p[3] == "1", preamp, p[5])
    }

    fun parse(lines: Sequence<String>): List<AutoEqOfflineEntry> = lines.mapNotNull(::parseLine).toList()

    /**
     * `P2289,6.1,1.57;L105,-4.2,0.70;H10000,-1.0,0.70` → AutoEq bands. P = peak, L = low shelf, H = high shelf, with the
     * Q AutoEq printed (shelves are converted to the engine's slope later, in [toAutoBands] / [AutoEqSafety]).
     */
    fun parseBands(raw: String): List<AutoEqBand> = raw.split(';').mapNotNull { token ->
        if (token.length < 2) return@mapNotNull null
        val type = when (token[0]) {
            'P' -> FilterType.PK
            'L' -> FilterType.LSC
            'H' -> FilterType.HSC
            else -> return@mapNotNull null
        }
        val v = token.substring(1).split(',')
        if (v.size != 3) return@mapNotNull null
        val fc = v[0].toDoubleOrNull() ?: return@mapNotNull null
        val gain = v[1].toDoubleOrNull() ?: return@mapNotNull null
        val q = v[2].toDoubleOrNull() ?: return@mapNotNull null
        if (fc <= 0.0 || q <= 0.0) null else AutoEqBand(fc, gain, q, type)
    }

    /** Loads (once, then from a soft cache) the bundled catalogue. Blocking: call from Dispatchers.IO. Empty on failure. */
    fun load(context: Context): List<AutoEqOfflineEntry> {
        cache?.get()?.let { return it }
        val list = runCatching {
            GZIPInputStream(context.assets.open(ASSET_NAME)).bufferedReader().useLines { parse(it) }
        }.getOrDefault(emptyList())
        if (list.isNotEmpty()) cache = SoftReference(list)
        return list
    }

    /**
     * The bundled measurement for one row of the online index: same model folder name, source and rig kind (taken from
     * its `results/<source>/<rig>/…` path). When a source measured the model on two rigs of the same kind, the bundle
     * keeps AutoEq's recommended one.
     */
    fun find(context: Context, name: String, source: String, path: String): AutoEqOfflineEntry? =
        pick(load(context), name, source, path)

    fun pick(catalogue: List<AutoEqOfflineEntry>, name: String, source: String, path: String): AutoEqOfflineEntry? {
        val rig = path.split('/').getOrElse(2) { "" }.lowercase()
        val kind = AutoEqRigType.entries.firstOrNull { it.code.isNotEmpty() && rig.contains(it.code) } ?: AutoEqRigType.UNKNOWN
        return catalogue.firstOrNull { it.name == name && it.source == source && it.type == kind }
    }
}
